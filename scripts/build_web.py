"""Generate web/data.js from the lexicon TSV so the web app and Python never drift apart.
Usage: python scripts/build_web.py [--check]"""
import csv, json, sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
d = root / "src" / "wanda" / "data"
rows = [r for r in (l for l in (d / "jv_id_seed.tsv").read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#"))]
entries = []
for r in csv.reader(rows, delimiter="\t"):
    if len(r) >= 4:
        entries.append([c.strip() for c in r[:4]] + [r[4].strip() if len(r) > 4 and r[4].strip() else "unreviewed", r[5].strip() if len(r) > 5 else ""])
prot = [w.strip() for w in (d / "id_common_words.txt").read_text(encoding="utf-8").splitlines() if w.strip() and not w.startswith("#")]
out = "/* GENERATED by scripts/build_web.py from the lexicon TSV. Do not edit by hand. */\n(typeof window !== 'undefined' ? window : globalThis).WANDA_DATA = " + json.dumps({"entries": entries, "protected": prot}, ensure_ascii=False) + ";\n"
target = root / "web" / "data.js"
if "--check" in sys.argv:
    sys.exit(0 if target.exists() and target.read_text(encoding="utf-8") == out else "web/data.js is out of date: run python scripts/build_web.py")
target.write_text(out, encoding="utf-8")
print("wrote", target, len(entries), "entries")
